async function seed() {
  if (process.env.NODE_ENV === "production") {
    console.error("Seed is disabled in production.");
    process.exit(1);
  }

  if (process.env.SEED_ENABLED !== "true") {
    console.error("Set SEED_ENABLED=true to run the seed.");
    process.exit(1);
  }

  const uri = process.env.MONGODB_URI ?? defaultUri;

  await mongoose.connect(uri);

  const forceReset = process.env.SEED_FORCE === "true";
  const existingDefaults = await Food.countDocuments({ source: "default" });

  if (existingDefaults > 0 && !forceReset) {
    console.log(
      `${existingDefaults} default foods already exist. Use SEED_FORCE=true to reset.`,
    );
    await mongoose.disconnect();
    process.exit(0);
  }

  if (forceReset) {
    await Food.deleteMany({ source: "default" });
    console.log("Default foods removed.");
  }

  const inserted = await Food.insertMany(defaultFoods);
  console.log(`${inserted.length} default foods seeded successfully.`);

  await mongoose.disconnect();
  process.exit(0);
}

seed().catch(async (error) => {
  console.error("Seed failed:", error);
  await mongoose.disconnect();
  process.exit(1);
});
